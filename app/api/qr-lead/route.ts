
import { NextRequest, NextResponse } from "next/server";
import nodemailer from "nodemailer";

export const runtime = "nodejs";

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();

    const email =
      typeof body.email === "string" ? body.email.trim() : "";
    const content =
      typeof body.content === "string" ? body.content.trim() : "";

    if (
      !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) ||
      email.length > 254
    ) {
      return NextResponse.json(
        { error: "Please enter a valid email address." },
        { status: 400 }
      );
    }

    if (!content || content.length > 2000) {
      return NextResponse.json(
        { error: "Please enter valid QR code content." },
        { status: 400 }
      );
    }

    const {
      SMTP_HOST,
      SMTP_PORT,
      SMTP_SECURE,
      SMTP_USER,
      SMTP_PASS,
      SMTP_FROM,
      QR_LEAD_EMAIL,
    } = process.env;

    if (
      !SMTP_HOST ||
      !SMTP_PORT ||
      !SMTP_USER ||
      !SMTP_PASS ||
      !SMTP_FROM ||
      !QR_LEAD_EMAIL
    ) {
      console.error("QR lead email configuration is incomplete.");

      return NextResponse.json(
        { error: "The email service is not configured." },
        { status: 500 }
      );
    }

    const transporter = nodemailer.createTransport({
      host: SMTP_HOST,
      port: Number(SMTP_PORT),
      secure: SMTP_SECURE === "true",
      auth: {
        user: SMTP_USER,
        pass: SMTP_PASS,
      },
      connectionTimeout: 15000,
      greetingTimeout: 10000,
      socketTimeout: 20000,
    });

    await transporter.sendMail({
      from: SMTP_FROM,
      to: QR_LEAD_EMAIL,
      replyTo: email,
      subject: "New QR Code Generator Lead - NexGenByte",
      text: [
        "A visitor used the NexGenByte QR Code Generator.",
        "",
        `Visitor email: ${email}`,
        `QR code content: ${content}`,
        "",
        "This notification was generated by the QR Code Generator.",
      ].join("\n"),
    });

    return NextResponse.json({ success: true });
  } catch (error) {
    console.error("QR lead email error:", error);

    return NextResponse.json(
      {
        error:
          "We couldn't send your request. Please try again in a moment.",
      },
      { status: 502 }
    );
  }
}
